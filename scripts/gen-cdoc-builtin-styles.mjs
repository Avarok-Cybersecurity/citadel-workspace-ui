#!/usr/bin/env node
/**
 * Writes src/lib/cdoc/generated/builtin-styles.ts: the style sheet a blank Citadel document
 * carries (cdoc-model's `StyleSheet::word_builtin()`), read from the vendored cdoc-wasm pair's
 * own `blank_model_json()`, so the ribbon's styles gallery names and previews exactly the
 * styles the engine applies. scripts/sync-cdoc-wasm.sh runs it after vendoring a pair, and
 * src/lib/cdoc/__tests__/builtin-styles.test.ts fails when the file and the pair disagree.
 *
 *   node scripts/gen-cdoc-builtin-styles.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const UI = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const glue = await import(join(UI, 'vendor/cdoc/cdoc_wasm.js'));
glue.initSync({ module: readFileSync(join(UI, 'public/cdoc/cdoc_wasm_bg.wasm')) });
const { styles } = JSON.parse(glue.blank_model_json());
writeFileSync(join(UI, 'src/lib/cdoc/generated/builtin-styles.ts'), [
  '// Generated by scripts/gen-cdoc-builtin-styles.mjs from the vendored cdoc-wasm blank_model_json(). Do not edit.',
  "import type { StyleSheet } from '../editor/style-sheet';",
  '',
  // One style per line: the sheet reads as a table and stays under the file-length cap.
  'export const BUILTIN_STYLE_SHEET: StyleSheet = {',
  `  defaults: ${JSON.stringify(styles.defaults)},`,
  '  styles: [',
  ...styles.styles.map((style) => `    ${JSON.stringify(style)},`),
  '  ],',
  '};',
  '',
].join('\n'));
